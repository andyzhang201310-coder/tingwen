const TABLES = { zh: ZH, en: EN };

let current = 'zh';

/** 设置值（zh-CN / en-US / auto）→ 实际语言 */
export function resolveLang(setting) {
  if (setting === 'en-US') return 'en';
  if (setting === 'zh-CN') return 'zh';
  const nav = (navigator.language || 'zh-CN').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

export function setLang(setting) {
  current = resolveLang(setting);
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
  return current;
}

export function getLang() {
  return current;
}

export function isEn() {
  return current === 'en';
}

/** 语言标签，给 Intl 用 */
export function locale() {
  return current === 'zh' ? 'zh-CN' : 'en-US';
}

/** 取词条；缺失时回退中文，再回退 key 本身，方便发现漏翻 */
export function T(key, vars) {
  const table = TABLES[current] || ZH;
  let out = table[key] ?? ZH[key] ?? key;
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
  }
  return out;
}

/** 词条是否存在（测试用） */
export function hasKey(key) {
  return key in ZH && key in EN;
}

export function langOptions() {
  return [
    { label: T('set.langZh'), value: 'zh-CN' },
    { label: T('set.langEn'), value: 'en-US' },
    { label: T('set.langAuto'), value: 'auto' },
  ];
}
